const LANGS=['it','fr','en'];
let LANG='it'; /* italien par défaut */
try{
  const q=new URLSearchParams(location.search).get('lang');
  LANG=LANGS.includes(q)?q:(localStorage.getItem('regola-lang')||'it');
}catch(e){}
if(!LANGS.includes(LANG))LANG='it';

const norm=s=>s.replace(/\s+/g,' ').trim();
function t(s){
  if(LANG==='fr')return s;
  const e=I18N[norm(s)];
  return e?e[LANG==='it'?0:1]:s;
}

const ATTRS=['placeholder','alt','title','aria-label'];
function applyLang(){
  document.documentElement.lang=LANG;
  if(!document.__frTitle)document.__frTitle=document.title;
  document.title=t(document.__frTitle);
  const w=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT,{acceptNode:n=>{
    const p=n.parentElement; if(!p)return 2;
    if(p.closest('script,style,svg,.lang,.watermark'))return 2;
    return norm(n.nodeValue)?1:2;
  }});
  let n;
  while((n=w.nextNode())){
    if(n.__fr===undefined)n.__fr=n.nodeValue;
    const src=n.__fr, key=norm(src);
    if(!I18N[key]&&LANG!=='fr')continue;
    const lead=src.match(/^\s*/)[0], trail=src.match(/\s*$/)[0];
    n.nodeValue=lead+t(key)+trail;
  }
  document.querySelectorAll('['+ATTRS.join('],[')+']').forEach(el=>{
    ATTRS.forEach(a=>{
      if(!el.hasAttribute(a))return;
      const k='data-fr-'+a;
      if(!el.hasAttribute(k))el.setAttribute(k,el.getAttribute(a));
      el.setAttribute(a,t(el.getAttribute(k)));
    });
  });
  document.querySelectorAll('.lang button').forEach(b=>b.classList.toggle('on',b.dataset.l===LANG));
}

function setLang(l){
  LANG=l;
  try{localStorage.setItem('regola-lang',l)}catch(e){}
  if(typeof window.onLangChange==='function')window.onLangChange();
  applyLang();
}

/* sélecteur FR · IT · EN dans l'en-tête */
(function(){
  const box=document.createElement('div');
  box.className='lang';
  box.setAttribute('role','group');
  box.innerHTML=LANGS.map(l=>`<button data-l="${l}" aria-label="${{fr:'Français',it:'Italiano',en:'English'}[l]}">${l.toUpperCase()}</button>`).join('');
  box.onclick=e=>{const b=e.target.closest('button');if(b&&b.dataset.l!==LANG)setLang(b.dataset.l)};
  const hact=document.querySelector('.hact');
  if(hact)hact.prepend(box);
  applyLang();
})();
